import java.util.Scanner;
import java.util.Stack;

public class Task4 {
    /*
    * •	Напишите метод, проверяющую правильность расстановки скобок в строке, введенной с клавиатуры. При правильной расстановке выполняются условия: количество открывающих и закрывающих скобок равно;
•	внутри любой пары открывающая–соответствующая закрывающая скобка, скобки расставлены правильно. В строке могут присутствовать как круглые, так и квадратные скобки (и др. символы). Каждой открывающей скобке соответствует закрывающая того же типа (круглой – круглая, квадратной – квадратная).

Пример неправильной расстановки: ( [ a) b]
Пример правильных входных данных: (a[b](f[(g)(g)]))

Программа должна вывести результат в виде сообщения, примеры:
•	Правильная строка
•	Ошибка отсутствие (
•	Ошибка отсутствие )
•	Ошибка отсутствие [
•	Ошибка отсутствие ]
*/
    // Метод для проверки правильности расстановки скобок
    public static String checkBrackets(String input) {
        Stack<Character> stack = new Stack<>();

        // Проходим по каждому символу строки
        for (int i = 0; i < input.length(); i++) {
            char c = input.charAt(i);

            // Если символ — открывающая скобка, добавляем в стек
            if (c == '(' || c == '[') {
                stack.push(c);
            }
            // Если символ — закрывающая круглая скобка
            else if (c == ')') {
                if (stack.isEmpty()) {
                    return "Ошибка: отсутствие (";
                }
                char top = stack.pop();
                if (top != '(') {
                    return "Ошибка: несоответствие скобок, ожидалась (";
                }
            }
            // Если символ — закрывающая квадратная скобка
            else if (c == ']') {
                if (stack.isEmpty()) {
                    return "Ошибка: отсутствие [";
                }
                char top = stack.pop();
                if (top != '[') {
                    return "Ошибка: несоответствие скобок, ожидалась [";
                }
            }
        }

        // После обработки строки проверяем, остались ли незакрытые скобки
        if (!stack.isEmpty()) {
            char top = stack.peek();
            if (top == '(') {
                return "Ошибка: отсутствие )";
            } else if (top == '[') {
                return "Ошибка: отсутствие ]";
            }
        }

        // Если стек пуст, строка корректна
        return "Правильная строка";
    }

    // Тестирование метода
    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);

        // Ввод строки с клавиатуры
        System.out.println("Введите строку для проверки скобок:");
        String input = scanner.nextLine();

        // Вывод результата проверки
        System.out.println(checkBrackets(input));

        scanner.close();
    }
}