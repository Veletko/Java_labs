public class task8 {
    public static void main(String[] args) {
 /*Зная скорость распространения звука в воздушной среде,
  можно вычислить расстояние до места удара молнии
  по времени между вспышкой и раскатом грома.
   Зная время в секундах между вспышкой и раскатом
   грома (константа в программе), вычислите
    расстояния до места удара молнии и выведите его на экран*/

        final double SPEED_OF_SOUND = 343.0; // скорость звука в воздухе (м/с) при 20°C
        final double TIME_BETWEEN = 5.0; // время между вспышкой и громом в секундах

        // Вычисление расстояния: расстояние = скорость × время
        double distance = SPEED_OF_SOUND * TIME_BETWEEN;

        System.out.println("Скорость звука: " + SPEED_OF_SOUND);
        System.out.printf("Время между вспышкой и громом: %.1f секунд%n", TIME_BETWEEN);
        System.out.printf("Расстояние до молнии: %.1f метров%n", distance);
        System.out.printf("Расстояние до молнии: %.1f километров%n", distance / 1000);
    }
}
